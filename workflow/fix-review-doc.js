// The completeness-critic mis-serialized its tool call: the `contradictions`
// array leaked into the `verdict` string as XML-ish <parameter> tags, and the
// real `contradictions` field came back undefined. This script reconstructs a
// clean 07-review-gaps-risks.md.
const fs = require('fs');
const path = require('path');

const OUT = process.argv[2];
const DEST = process.argv[3] || 'D:\\Assisty';
const parsed = JSON.parse(fs.readFileSync(OUT, 'utf8'));
const data = parsed.result || parsed;
const c = data.critique || {};

let verdict = String(c.verdict || '');
let contradictions = Array.isArray(c.contradictions) ? c.contradictions : [];

// Split off anything that leaked after a stray </parameter> or <parameter ...>
const tagIdx = verdict.search(/<\/?parameter\b/i);
let leaked = '';
if (tagIdx !== -1) {
  leaked = verdict.slice(tagIdx);
  verdict = verdict.slice(0, tagIdx).trim();
}

// Try to recover the contradictions JSON array embedded in the leaked text.
if (!contradictions.length && leaked) {
  const m = leaked.match(/name="contradictions">\s*(\[[\s\S]*?\])/i);
  if (m) {
    try { contradictions = JSON.parse(m[1]); } catch (e) { /* leave empty */ }
  }
}

let md = '# Assisty — Architecture Review: Gaps, Risks & Open Decisions\n\n';
md += '> Auto-generated by the completeness-critic pass of the architecture workflow.\n\n';
if (verdict) md += '## Verdict\n\n' + verdict + '\n\n';
const sec = (title, arr) => {
  if (Array.isArray(arr) && arr.length) {
    md += '## ' + title + '\n\n' + arr.map(x => '- ' + x).join('\n') + '\n\n';
  }
};
sec('Contradictions to resolve', contradictions);
sec('Gaps to close', c.gaps);
sec('Open product decisions for you', c.openProductDecisions);
sec('Top risks', c.topRisks);

const target = path.join(DEST, 'docs', '07-review-gaps-risks.md');
fs.writeFileSync(target, md, 'utf8');
console.log('Rewrote ' + target + ' (' + md.length + ' chars)');
console.log('Recovered contradictions: ' + contradictions.length);
